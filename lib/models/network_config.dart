import 'dart:convert';

/// EasyTier 组网配置模型
class NetworkConfig {
  final String id;
  String profileName;
  String networkName;
  String networkSecret;
  bool useDhcp;
  String ipv4;
  String ipv6;
  List<String> peers;
  List<String> externalNodes;
  List<String> proxyNetworks;
  int rpcPort;
  int listenPort;
  bool enableEncryption;
  String additionalArgs;

  NetworkConfig({
    required this.id,
    this.profileName = '默认网络',
    this.networkName = 'easytier_net',
    this.networkSecret = '',
    this.useDhcp = true,
    this.ipv4 = '10.144.144.1',
    this.ipv6 = '',
    List<String>? peers,
    List<String>? externalNodes,
    List<String>? proxyNetworks,
    this.rpcPort = 15888,
    this.listenPort = 11010,
    this.enableEncryption = true,
    this.additionalArgs = '',
  })  : peers = peers ?? ['tcp://public.easytier.cn:11010'],
        externalNodes = externalNodes ?? [],
        proxyNetworks = proxyNetworks ?? [];

  /// 生成一份全新的默认配置
  factory NetworkConfig.createDefault({String? name}) {
    final timestamp = DateTime.now().millisecondsSinceEpoch;
    return NetworkConfig(
      id: 'cfg_$timestamp',
      profileName: name ?? '新建网络配置',
      networkName: 'my_easytier',
      networkSecret: '',
      useDhcp: true,
      ipv4: '10.144.144.1',
      peers: ['tcp://public.easytier.cn:11010'],
      externalNodes: [],
      proxyNetworks: [],
      rpcPort: 15888,
      listenPort: 11010,
      enableEncryption: true,
      additionalArgs: '',
    );
  }

  /// 转换为 easytier-core 启动参数
  List<String> toCommandLineArgs() {
    final List<String> args = [];

    // 网络名称与密码
    if (networkName.isNotEmpty) {
      args.addAll(['--network-name', networkName]);
    }
    if (networkSecret.isNotEmpty) {
      args.addAll(['--network-secret', networkSecret]);
    }

    // IP 配置
    if (useDhcp) {
      args.add('-d'); // 启用 DHCP
    } else if (ipv4.isNotEmpty) {
      args.addAll(['-i', ipv4]);
    }

    if (ipv6.isNotEmpty) {
      args.addAll(['--ipv6', ipv6]);
    }

    // Peers
    for (final peer in peers) {
      if (peer.trim().isNotEmpty) {
        args.addAll(['-p', peer.trim()]);
      }
    }

    // External nodes
    for (final ext in externalNodes) {
      if (ext.trim().isNotEmpty) {
        args.addAll(['-e', ext.trim()]);
      }
    }

    // Proxy networks (子网代理)
    for (final proxy in proxyNetworks) {
      if (proxy.trim().isNotEmpty) {
        args.addAll(['-n', proxy.trim()]);
      }
    }

    // RPC Portal
    if (rpcPort > 0) {
      args.addAll(['--rpc-portal', '127.0.0.1:$rpcPort']);
    }

    // Listeners
    if (listenPort > 0) {
      args.addAll(['--listeners', 'tcp://0.0.0.0:$listenPort', 'udp://0.0.0.0:$listenPort']);
    }

    // 解析用户附加参数
    if (additionalArgs.trim().isNotEmpty) {
      final extraParts = additionalArgs
          .trim()
          .split(RegExp(r'\s+'))
          .where((s) => s.isNotEmpty);
      args.addAll(extraParts);
    }

    return args;
  }

  /// 转换为 TOML 配置格式文本
  String toToml() {
    final buffer = StringBuffer();
    buffer.writeln('# EasyTier Configuration File');
    buffer.writeln('# Generated by EasyTier GUI');
    buffer.writeln('');
    buffer.writeln('network_name = "$networkName"');
    if (networkSecret.isNotEmpty) {
      buffer.writeln('network_secret = "$networkSecret"');
    }
    buffer.writeln('dhcp = $useDhcp');
    if (!useDhcp && ipv4.isNotEmpty) {
      buffer.writeln('ipv4 = "$ipv4"');
    }
    if (ipv6.isNotEmpty) {
      buffer.writeln('ipv6 = "$ipv6"');
    }
    buffer.writeln('');

    if (peers.isNotEmpty) {
      buffer.writeln('peers = [');
      for (final p in peers) {
        if (p.trim().isNotEmpty) {
          buffer.writeln('  "${p.trim()}",');
        }
      }
      buffer.writeln(']');
      buffer.writeln('');
    }

    if (proxyNetworks.isNotEmpty) {
      buffer.writeln('proxy_networks = [');
      for (final pn in proxyNetworks) {
        if (pn.trim().isNotEmpty) {
          buffer.writeln('  "${pn.trim()}",');
        }
      }
      buffer.writeln(']');
      buffer.writeln('');
    }

    buffer.writeln('rpc_portal = "127.0.0.1:$rpcPort"');
    return buffer.toString();
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'profileName': profileName,
        'networkName': networkName,
        'networkSecret': networkSecret,
        'useDhcp': useDhcp,
        'ipv4': ipv4,
        'ipv6': ipv6,
        'peers': peers,
        'externalNodes': externalNodes,
        'proxyNetworks': proxyNetworks,
        'rpcPort': rpcPort,
        'listenPort': listenPort,
        'enableEncryption': enableEncryption,
        'additionalArgs': additionalArgs,
      };

  factory NetworkConfig.fromJson(Map<String, dynamic> json) => NetworkConfig(
        id: json['id'] as String? ?? 'cfg_${DateTime.now().millisecondsSinceEpoch}',
        profileName: json['profileName'] as String? ?? '默认配置',
        networkName: json['networkName'] as String? ?? '',
        networkSecret: json['networkSecret'] as String? ?? '',
        useDhcp: json['useDhcp'] as bool? ?? true,
        ipv4: json['ipv4'] as String? ?? '10.144.144.1',
        ipv6: json['ipv6'] as String? ?? '',
        peers: (json['peers'] as List<dynamic>?)?.map((e) => e.toString()).toList() ??
            ['tcp://public.easytier.cn:11010'],
        externalNodes: (json['externalNodes'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
        proxyNetworks: (json['proxyNetworks'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
        rpcPort: json['rpcPort'] as int? ?? 15888,
        listenPort: json['listenPort'] as int? ?? 11010,
        enableEncryption: json['enableEncryption'] as bool? ?? true,
        additionalArgs: json['additionalArgs'] as String? ?? '',
      );

  NetworkConfig clone({String? newId, String? newName}) {
    return NetworkConfig.fromJson(jsonDecode(jsonEncode(toJson())))
      ..profileName = newName ?? '$profileName (副本)';
  }
}


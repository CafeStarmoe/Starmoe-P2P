import 'dart:convert';
import 'package:yaml/yaml.dart';

/// EasyTier 组网配置模型
class NetworkConfig {
  final String id;
  String profileName;
  String networkName;
  String networkSecret;
  bool useDhcp;
  String ipv4;
  String ipv6;
  List<String> peers;
  List<String> externalNodes;
  List<String> proxyNetworks;
  int rpcPort;
  int listenPort;
  bool enableEncryption;
  String additionalArgs;

  NetworkConfig({
    required this.id,
    this.profileName = '默认网络',
    this.networkName = 'easytier_net',
    this.networkSecret = '',
    this.useDhcp = true,
    this.ipv4 = '10.144.144.1',
    this.ipv6 = '',
    List<String>? peers,
    List<String>? externalNodes,
    List<String>? proxyNetworks,
    this.rpcPort = 15888,
    this.listenPort = 11010,
    this.enableEncryption = true,
    this.additionalArgs = '',
  })  : peers = peers ?? ['tcp://public.easytier.cn:11010'],
        externalNodes = externalNodes ?? [],
        proxyNetworks = proxyNetworks ?? [];

  /// 生成一份全新的默认配置
  factory NetworkConfig.createDefault({String? name}) {
    final timestamp = DateTime.now().millisecondsSinceEpoch;
    return NetworkConfig(
      id: 'cfg_$timestamp',
      profileName: name ?? '新建网络配置',
      networkName: 'my_easytier',
      networkSecret: '',
      useDhcp: true,
      ipv4: '10.144.144.1',
      peers: ['tcp://public.easytier.cn:11010'],
      externalNodes: [],
      proxyNetworks: [],
      rpcPort: 15888,
      listenPort: 11010,
      enableEncryption: true,
      additionalArgs: '',
    );
  }

  /// 转换为 easytier-core 启动参数
  List<String> toCommandLineArgs() {
    final List<String> args = [];

    // 网络名称与密码
    if (networkName.isNotEmpty) {
      args.addAll(['--network-name', networkName]);
    }
    if (networkSecret.isNotEmpty) {
      args.addAll(['--network-secret', networkSecret]);
    }

    // IP 配置
    if (useDhcp) {
      args.add('-d'); // 启用 DHCP
    } else if (ipv4.isNotEmpty) {
      args.addAll(['-i', ipv4]);
    }

    if (ipv6.isNotEmpty) {
      args.addAll(['--ipv6', ipv6]);
    }

    // Peers
    for (final peer in peers) {
      if (peer.trim().isNotEmpty) {
        args.addAll(['-p', peer.trim()]);
      }
    }

    // External nodes
    for (final ext in externalNodes) {
      if (ext.trim().isNotEmpty) {
        args.addAll(['-e', ext.trim()]);
      }
    }

    // Proxy networks (子网代理)
    for (final proxy in proxyNetworks) {
      if (proxy.trim().isNotEmpty) {
        args.addAll(['-n', proxy.trim()]);
      }
    }

    // RPC Portal
    if (rpcPort > 0) {
      args.addAll(['--rpc-portal', '127.0.0.1:$rpcPort']);
    }

    // Listeners
    if (listenPort > 0) {
      args.addAll(['--listeners', 'tcp://0.0.0.0:$listenPort', 'udp://0.0.0.0:$listenPort']);
    }

    // 解析用户附加参数
    if (additionalArgs.trim().isNotEmpty) {
      final extraParts = additionalArgs
          .trim()
          .split(RegExp(r'\s+'))
          .where((s) => s.isNotEmpty);
      args.addAll(extraParts);
    }

    return args;
  }

  /// 转换为 YAML 配置格式文本 (原版 config.yaml)
  String toYaml() {
    final buffer = StringBuffer();
    buffer.writeln('# EasyTier YAML Configuration File');
    buffer.writeln('# Generated by EasyTier GUI');
    buffer.writeln('');
    buffer.writeln('network_name: "$networkName"');
    if (networkSecret.isNotEmpty) {
      buffer.writeln('network_secret: "$networkSecret"');
    }
    buffer.writeln('dhcp: $useDhcp');
    if (!useDhcp && ipv4.isNotEmpty) {
      buffer.writeln('ipv4: "$ipv4"');
    }
    if (ipv6.isNotEmpty) {
      buffer.writeln('ipv6: "$ipv6"');
    }
    buffer.writeln('');

    if (peers.isNotEmpty) {
      buffer.writeln('peers:');
      for (final p in peers) {
        if (p.trim().isNotEmpty) {
          buffer.writeln('  - "${p.trim()}"');
        }
      }
      buffer.writeln('');
    }

    if (externalNodes.isNotEmpty) {
      buffer.writeln('external_nodes:');
      for (final ext in externalNodes) {
        if (ext.trim().isNotEmpty) {
          buffer.writeln('  - "${ext.trim()}"');
        }
      }
      buffer.writeln('');
    }

    if (proxyNetworks.isNotEmpty) {
      buffer.writeln('proxy_networks:');
      for (final pn in proxyNetworks) {
        if (pn.trim().isNotEmpty) {
          buffer.writeln('  - "${pn.trim()}"');
        }
      }
      buffer.writeln('');
    }

    buffer.writeln('rpc_portal: "127.0.0.1:$rpcPort"');
    if (listenPort > 0) {
      buffer.writeln('listeners:');
      buffer.writeln('  - "tcp://0.0.0.0:$listenPort"');
      buffer.writeln('  - "udp://0.0.0.0:$listenPort"');
    }

    return buffer.toString();
  }

  /// 从 YAML 格式字符串解析并更新/构建 NetworkConfig
  static NetworkConfig fromYaml(String yamlString, {String? defaultName}) {
    final doc = loadYaml(yamlString);
    if (doc is! Map) {
      throw const FormatException('无效的 YAML 配置文件格式');
    }

    // 辅助转换 key
    dynamic getVal(List<String> keys) {
      for (final k in keys) {
        if (doc.containsKey(k)) return doc[k];
      }
      return null;
    }

    final netName = (getVal(['network_name', 'networkName', 'net_name']) ?? '').toString();
    final netSecret = (getVal(['network_secret', 'networkSecret', 'secret']) ?? '').toString();

    bool dhcp = true;
    final dhcpVal = getVal(['dhcp', 'use_dhcp', 'useDhcp']);
    if (dhcpVal is bool) {
      dhcp = dhcpVal;
    }

    final ip4 = (getVal(['ipv4', 'ip']) ?? '10.144.144.1').toString();
    final ip6 = (getVal(['ipv6']) ?? '').toString();

    List<String> peerList = [];
    final peersVal = getVal(['peers', 'peer']);
    if (peersVal is List) {
      peerList = peersVal.map((e) => e.toString()).toList();
    }

    List<String> extList = [];
    final extVal = getVal(['external_nodes', 'externalNodes', 'external_node']);
    if (extVal is List) {
      extList = extVal.map((e) => e.toString()).toList();
    }

    List<String> proxyList = [];
    final proxyVal = getVal(['proxy_networks', 'proxyNetworks', 'proxy_network']);
    if (proxyVal is List) {
      proxyList = proxyVal.map((e) => e.toString()).toList();
    }

    int rpc = 15888;
    final rpcPortalVal = getVal(['rpc_portal', 'rpcPortal'])?.toString();
    if (rpcPortalVal != null) {
      final match = RegExp(r':(\d+)$').firstMatch(rpcPortalVal);
      if (match != null) {
        rpc = int.tryParse(match.group(1)!) ?? 15888;
      }
    } else {
      final rpcVal = getVal(['rpc_port', 'rpcPort']);
      if (rpcVal != null) {
        rpc = int.tryParse(rpcVal.toString()) ?? 15888;
      }
    }

    int listen = 11010;
    final listenersVal = getVal(['listeners', 'listener']);
    if (listenersVal is List && listenersVal.isNotEmpty) {
      final firstListener = listenersVal.first.toString();
      final match = RegExp(r':(\d+)$').firstMatch(firstListener);
      if (match != null) {
        listen = int.tryParse(match.group(1)!) ?? 11010;
      }
    }

    final timestamp = DateTime.now().millisecondsSinceEpoch;
    final profileName = defaultName ?? (netName.isNotEmpty ? '配置_$netName' : '导入配置_$timestamp');

    return NetworkConfig(
      id: 'cfg_$timestamp',
      profileName: profileName,
      networkName: netName,
      networkSecret: netSecret,
      useDhcp: dhcp,
      ipv4: ip4,
      ipv6: ip6,
      peers: peerList.isNotEmpty ? peerList : ['tcp://public.easytier.cn:11010'],
      externalNodes: extList,
      proxyNetworks: proxyList,
      rpcPort: rpc,
      listenPort: listen,
      enableEncryption: true,
      additionalArgs: '',
    );
  }

  /// 转换为 TOML 配置格式文本
  String toToml() {
    final buffer = StringBuffer();
    buffer.writeln('# EasyTier Configuration File');
    buffer.writeln('# Generated by EasyTier GUI');
    buffer.writeln('');
    buffer.writeln('network_name = "$networkName"');
    if (networkSecret.isNotEmpty) {
      buffer.writeln('network_secret = "$networkSecret"');
    }
    buffer.writeln('dhcp = $useDhcp');
    if (!useDhcp && ipv4.isNotEmpty) {
      buffer.writeln('ipv4 = "$ipv4"');
    }
    if (ipv6.isNotEmpty) {
      buffer.writeln('ipv6 = "$ipv6"');
    }
    buffer.writeln('');

    if (peers.isNotEmpty) {
      buffer.writeln('peers = [');
      for (final p in peers) {
        if (p.trim().isNotEmpty) {
          buffer.writeln('  "${p.trim()}",');
        }
      }
      buffer.writeln(']');
      buffer.writeln('');
    }

    if (proxyNetworks.isNotEmpty) {
      buffer.writeln('proxy_networks = [');
      for (final pn in proxyNetworks) {
        if (pn.trim().isNotEmpty) {
          buffer.writeln('  "${pn.trim()}",');
        }
      }
      buffer.writeln(']');
      buffer.writeln('');
    }

    buffer.writeln('rpc_portal = "127.0.0.1:$rpcPort"');
    return buffer.toString();
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'profileName': profileName,
        'networkName': networkName,
        'networkSecret': networkSecret,
        'useDhcp': useDhcp,
        'ipv4': ipv4,
        'ipv6': ipv6,
        'peers': peers,
        'externalNodes': externalNodes,
        'proxyNetworks': proxyNetworks,
        'rpcPort': rpcPort,
        'listenPort': listenPort,
        'enableEncryption': enableEncryption,
        'additionalArgs': additionalArgs,
      };

  factory NetworkConfig.fromJson(Map<String, dynamic> json) => NetworkConfig(
        id: json['id'] as String? ?? 'cfg_${DateTime.now().millisecondsSinceEpoch}',
        profileName: json['profileName'] as String? ?? '默认配置',
        networkName: json['networkName'] as String? ?? '',
        networkSecret: json['networkSecret'] as String? ?? '',
        useDhcp: json['useDhcp'] as bool? ?? true,
        ipv4: json['ipv4'] as String? ?? '10.144.144.1',
        ipv6: json['ipv6'] as String? ?? '',
        peers: (json['peers'] as List<dynamic>?)?.map((e) => e.toString()).toList() ??
            ['tcp://public.easytier.cn:11010'],
        externalNodes: (json['externalNodes'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
        proxyNetworks: (json['proxyNetworks'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
        rpcPort: json['rpcPort'] as int? ?? 15888,
        listenPort: json['listenPort'] as int? ?? 11010,
        enableEncryption: json['enableEncryption'] as bool? ?? true,
        additionalArgs: json['additionalArgs'] as String? ?? '',
      );

  NetworkConfig clone({String? newId, String? newName}) {
    return NetworkConfig.fromJson(jsonDecode(jsonEncode(toJson())))
      ..profileName = newName ?? '$profileName (副本)';
  }
}
